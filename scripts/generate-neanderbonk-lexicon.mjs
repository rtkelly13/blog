#!/usr/bin/env node
/**
 * Builds the NeanderBonk syllable lexicon from the CMU Pronouncing Dictionary.
 *
 * Run manually (`pnpm neanderbonk:lexicon`), never as part of `pnpm build` —
 * it needs the network, and the output is committed. Provenance lives here so
 * the data file is reproducible rather than mysterious.
 *
 * A syllable count is the number of phones carrying a stress digit (CMUdict
 * marks every vowel with 0/1/2), which is exactly one per syllable. Words with
 * several pronunciations get a min/max range — "fire" is one syllable or two
 * depending on who is saying it, and the referee gives the poet the benefit of
 * that doubt.
 *
 * Output format (`public/neanderbonk/syllables.txt`), one bucket per line:
 *
 *   1 cat dog run …          exactly one syllable
 *   2 table apple …          exactly two
 *   1-2 fire hour poem …     ambiguous, one *or* two
 *
 * Space-separated words keep it far smaller than JSON, and it gzips hard.
 */

import { createWriteStream } from 'node:fs';
import { mkdir, stat } from 'node:fs/promises';
import path from 'node:path';
import { pipeline } from 'node:stream/promises';

const SOURCE =
  'https://raw.githubusercontent.com/cmusphinx/cmudict/master/cmudict.dict';
const OUT_DIR = path.join(process.cwd(), 'public', 'neanderbonk');
const OUT_FILE = path.join(OUT_DIR, 'syllables.txt');

/** Longer than this is never a party-game clue; trimming keeps the file lean. */
const MAX_WORD_LENGTH = 20;

async function fetchDict() {
  const response = await fetch(SOURCE);
  if (!response.ok) {
    throw new Error(`CMUdict fetch failed: ${response.status}`);
  }
  return response.text();
}

/** @returns {Map<string, {min: number, max: number}>} */
function parseDict(text) {
  const counts = new Map();

  for (const rawLine of text.split('\n')) {
    // CMUdict puts trailing comments after ` #`.
    const line = rawLine.split(' #')[0].trim();
    if (!line) continue;

    const parts = line.split(/\s+/);
    // `word(2)` is an alternate pronunciation of `word`; fold it into the range.
    const word = parts[0].replace(/\(\d+\)$/, '').toLowerCase();

    // Alphabetic only: drops "'bout", "1990", hyphenated compounds and the
    // punctuation entries. The heuristic fallback covers whatever this loses.
    if (!/^[a-z]+$/.test(word)) continue;
    if (word.length > MAX_WORD_LENGTH) continue;

    const syllables = parts
      .slice(1)
      .filter((phone) => /\d$/.test(phone)).length;
    if (syllables < 1) continue;

    const seen = counts.get(word);
    if (seen) {
      seen.min = Math.min(seen.min, syllables);
      seen.max = Math.max(seen.max, syllables);
    } else {
      counts.set(word, { min: syllables, max: syllables });
    }
  }

  return counts;
}

/** Groups words into `min-max` buckets so each range is written once. */
function toBuckets(counts) {
  const buckets = new Map();
  for (const [word, { min, max }] of counts) {
    const key = min === max ? `${min}` : `${min}-${max}`;
    const bucket = buckets.get(key);
    if (bucket) bucket.push(word);
    else buckets.set(key, [word]);
  }

  // Sort buckets by min then span, and words alphabetically — a stable file
  // means a regenerated lexicon produces an empty diff when CMUdict hasn't moved.
  const ordered = [...buckets.entries()].sort((a, b) => {
    const [aMin, aMax = aMin] = a[0].split('-').map(Number);
    const [bMin, bMax = bMin] = b[0].split('-').map(Number);
    return aMin - bMin || aMax - bMax;
  });
  for (const [, words] of ordered) words.sort();
  return ordered;
}

async function main() {
  process.stdout.write(`Fetching ${SOURCE}\n`);
  const counts = parseDict(await fetchDict());
  const buckets = toBuckets(counts);

  await mkdir(OUT_DIR, { recursive: true });
  const out = createWriteStream(OUT_FILE);
  await pipeline(
    (function* lines() {
      yield '# NeanderBonk syllable lexicon\n';
      yield '# Generated by scripts/generate-neanderbonk-lexicon.mjs — do not edit by hand.\n';
      yield '# Source: CMU Pronouncing Dictionary (cmusphinx/cmudict), BSD-2-Clause.\n';
      yield '# Format: "<min>[-<max>] word word …" — one bucket per line.\n';
      for (const [range, words] of buckets) {
        yield `${range} ${words.join(' ')}\n`;
      }
    })(),
    out,
  );

  const { size } = await stat(OUT_FILE);
  process.stdout.write(
    `Wrote ${counts.size} words in ${buckets.length} buckets ` +
      `→ public/neanderbonk/syllables.txt (${(size / 1024).toFixed(0)} KB)\n`,
  );
  for (const [range, words] of buckets) {
    process.stdout.write(`  ${range.padEnd(5)} ${words.length}\n`);
  }
}

main().catch((error) => {
  process.stderr.write(`${error.stack ?? error}\n`);
  process.exit(1);
});
